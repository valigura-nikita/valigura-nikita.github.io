function calculatePotion() {
    const select = document.getElementById('potionSelect');
    const recipeBox = document.getElementById('recipeBox');
    const container = document.getElementById('stepsContainer');

    const selectedPotion = select.value;

    // Якщо нічого не обрано, ховаємо блок
    if (!selectedPotion) {
        recipeBox.style.display = 'none';
        return;
    }

    // Очищуємо попередній рецепт
    container.innerHTML = '';

    // Беремо масив кроків для обраного зілля
    const steps = potionsData[selectedPotion];

    // Створюємо HTML для кожного кроку
    steps.forEach((stepText, index) => {
        const stepDiv = document.createElement('div');
        stepDiv.className = 'step';

        stepDiv.innerHTML = `
            <div class="step-num">${index + 1}</div>
            <div class="step-text">${stepText}</div>
        `;

        container.appendChild(stepDiv);
    });

    // Показуємо блок з рецептом
    recipeBox.style.display = 'block';
}

window.addEventListener('load', calculatePotion())